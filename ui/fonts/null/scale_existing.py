"""Make slightly larger ASCII music faces from the repository's uncompressed LVGL fonts.
Retains the original licences (Null/DejaVu, Doto OFL, IBM Plex OFL).
International characters use the runtime's existing fallback chain.
"""
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont
u=Path(__file__).resolve().parents[2]
out=['/* Generated by fonts/null/scale_existing.py. See original font files and licences. */','#include "lvgl/lvgl.h"']
def emit(source,name,ratio):
    s=(u/source).read_text()
    def block(symbol):return re.search(r'\b'+symbol+r'\[\]\s*=\s*\{(.*?)\};',s,re.S).group(1)
    bitmap=block('glyph_bitmap');desc=block('glyph_dsc')
    bitmap=re.sub(r'/\*.*?\*/','',bitmap,flags=re.S)
    raw=[int(v,0) for v in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b',bitmap)]
    entries=re.findall(r'\{([^{}]+)\}',desc)
    glyphs=[]
    for ent in entries:
        glyphs.append({k:int(v) for k,v in re.findall(r'\.(\w+)\s*=\s*(-?\d+)',ent)})
    data=[];ds=['{0}']
    for g in glyphs[1:96]:
        w,h=g['box_w'],g['box_h'];nw,nh=round(w*ratio),round(h*ratio)
        start=g['bitmap_index'];size=w*h
        values=[((raw[start+i//2]>>(4 if i%2==0 else 0))&15)*17 for i in range(size)]
        pixels=[]
        if size:
            im=Image.new('L',(w,h));im.putdata(values);im=im.resize((nw,nh),Image.Resampling.LANCZOS)
            pixels=[min(15,max(0,round(v/17))) for v in im.getdata()]
        ds.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}'%(len(data),round(g['adv_w']*ratio),nw,nh,round(g['ofs_x']*ratio),round(g['ofs_y']*ratio)))
        if len(pixels)%2:pixels.append(0)
        data += [(pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2)]
    line=int(re.findall(r'\.line_height\s*=\s*(\d+)',s)[-1]);base=int(re.findall(r'\.base_line\s*=\s*(\d+)',s)[-1])
    write(name,data,ds,round(line*ratio),round(base*ratio),4)
def write(name,data,ds,line,base,bpp):
    out.extend([f'static const uint8_t {name}_bits[]={{'+','.join(map(str,data))+'};',f'static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[]={{'+','.join(ds)+'};',f'static const lv_font_fmt_txt_cmap_t {name}_map[]={{{{.range_start=32,.range_length=95,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}}};',f'static const lv_font_fmt_txt_dsc_t {name}_dsc={{.glyph_bitmap={name}_bits,.glyph_dsc={name}_glyphs,.cmaps={name}_map,.cmap_num=1,.bpp={bpp}}};',f'const lv_font_t {name}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={line},.base_line={base},.dsc=&{name}_dsc}};'])
# Read the original 5x7 alphabet without executing generate.py's output side effect.
ns={'__file__':str(u/'fonts/null/generate.py')};s=(u/'fonts/null/generate.py').read_text().split('from PIL import')[0];exec(s,ns)
for size in (16,24):
    w=round(size*5/7);adv=w+round(size/7);data=[];ds=['{0}']
    for code in range(32,127):
        pat=ns['patterns'].get(chr(code).upper())
        if pat is None:
            im=Image.new('L',(5,7));ImageDraw.Draw(im).text((0,-2),chr(code),font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',8),fill=255)
            pat=[''.join('1' if im.getpixel((x,y))>=100 else '0' for x in range(5)) for y in range(7)]
        bits=[int(pat[min(6,y*7//size)][min(4,x*5//w)]) for y in range(size) for x in range(w)]
        ds.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d}'%(len(data),adv*16,w,size))
        data += [sum(v<<(7-j) for j,v in enumerate(bits[i:i+8])) for i in range(0,len(bits),8)]
    write(f'null_pixel_{size}',data,ds,size+2,0,1)
emit('font_dot_28.c','null_dot_31',31/28)
emit('font_mono_24.c','null_mono_27',27/24)
emit('font_weather16.c','null_weather_32',2)
for i,line in enumerate(out):
    if line.startswith('static const lv_font_fmt_txt_cmap_t null_weather_32_map'):
        out[i]='static const uint16_t null_weather_32_unicode[]={0,0x7f,0xa4,0xa6,0x142,0x143,0x299};\nstatic const lv_font_fmt_txt_cmap_t null_weather_32_map[]={{.range_start=61507,.range_length=666,.glyph_id_start=1,.unicode_list=null_weather_32_unicode,.list_length=7,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};'

(u/'font_null_music.c').write_text('\n'.join(out)+'\n')
