"""Null QS: Font Awesome 4.7 glyphs (OFL-1.1, licenses/OFL-1.1-FontAwesome.txt).
Source: https://github.com/FortAwesome/Font-Awesome/tree/v4.7.0/fonts
Rasterize the original vector glyphs at 30px; tint at runtime with theme ink.
"""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
p=Path(__file__).resolve().parent
codes=sorted({0xf1eb,0xf293,0xf02d,0xf021,0xf1e6,0xf013,0xf1de,0xf002,0xf0cb,0xf051,0xf0ca,0xf185,0xf001,0xf05a,0xf03e,0xf07b,0xf004})
f=ImageFont.truetype(str(p/'FontAwesome.ttf'),30);data=[];ds=['{0}'];top=min(f.getbbox(chr(c),anchor='ls')[1] for c in codes);bottom=max(f.getbbox(chr(c),anchor='ls')[3] for c in codes)
for code in codes:
 ch=chr(code);left,t,right,b=f.getbbox(ch,anchor='ls');w,h=right-left,b-t
 im=Image.new('L',(w,h));ImageDraw.Draw(im).text((-left,-t),ch,font=f,fill=255,anchor='ls');bits=[round(v/17) for v in im.getdata()]
 ds.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}'%(len(data),round(f.getlength(ch)*16),w,h,left,-b))
 if len(bits)%2:bits.append(0)
 data.extend((bits[i]<<4)|bits[i+1] for i in range(0,len(bits),2))
s='''/* Font Awesome 4.7 glyphs, OFL-1.1. Generated by fonts/null/qs/generate.py. */
#include "lvgl/lvgl.h"
'''
s+='static const uint8_t bits[]={'+','.join(map(str,data))+'};\n'
s+='static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={'+','.join(ds)+'};\n'
s+='static const uint16_t unicodes[]={'+','.join(str(c-codes[0]) for c in codes)+'};\n'
s+='static const lv_font_fmt_txt_cmap_t maps[]={{.range_start=%d,.range_length=%d,.glyph_id_start=1,.unicode_list=unicodes,.list_length=%d,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};\n'%(codes[0],codes[-1]-codes[0]+1,len(codes))
s+='static const lv_font_fmt_txt_dsc_t dsc={.glyph_bitmap=bits,.glyph_dsc=glyphs,.cmaps=maps,.cmap_num=1,.bpp=4};\n'
s+='const lv_font_t null_qs_icons_30={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=%d,.base_line=%d,.dsc=&dsc};\n'%(bottom-top,bottom)
(p.parents[2]/'font_null_qs.c').write_text(s)
