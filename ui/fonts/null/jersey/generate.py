"""Generate Null's Jersey / Pixelify pairing. Sources and OFL licences are adjacent.
Uses Pillow FreeType at the approved specimen sizes; ASCII uses these faces,
other characters retain Null's existing international fallback chain.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
p=Path(__file__).resolve().parent
out=['/* Generated by fonts/null/jersey/generate.py; font glyphs licensed OFL-1.1. */','#include "lvgl/lvgl.h"']
for name,file,size in [('null_jersey_42','Jersey10-Regular.ttf',42),('null_pixelify_22','PixelifySans.ttf',22),('null_pixelify_20','PixelifySans.ttf',20),('null_handjet_38','Handjet.ttf',38),('null_vt323_27','VT323.ttf',27),('null_vt323_24','VT323.ttf',24),('null_vt323_18','VT323.ttf',18),('null_vt323_21','VT323.ttf',21)]:
 f=ImageFont.truetype(str(p/file),size)
 if file=='Handjet.ttf':f.set_variation_by_axes([700,1,2])
 top=f.getbbox('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789',anchor='ls')[1]
 bottom=max(f.getbbox(chr(c),anchor='ls')[3] for c in range(32,127))
 data=[];ds=['{0}']
 for c in range(32,127):
  ch=chr(c);left,t,right,b=f.getbbox(ch,anchor='ls');w=right-left;h=b-t
  im=Image.new('L',(max(w,1),max(h,1)));ImageDraw.Draw(im).text((-left,-t),ch,font=f,fill=255,anchor='ls')
  pixels=[round(v/17) for v in im.getdata()] if w*h else []
  ds.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}'%(len(data),round(f.getlength(ch)*16),w,h,left,-b))
  if len(pixels)%2:pixels.append(0)
  data.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
 out += [f'static const uint8_t {name}_bits[]={{'+','.join(map(str,data))+'};',f'static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[]={{'+','.join(ds)+'};',f'static const lv_font_fmt_txt_cmap_t {name}_map[]={{{{.range_start=32,.range_length=95,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}}};',f'static const lv_font_fmt_txt_dsc_t {name}_dsc={{.glyph_bitmap={name}_bits,.glyph_dsc={name}_glyphs,.cmaps={name}_map,.cmap_num=1,.bpp=4}};',f'const lv_font_t {name}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={bottom-top+1},.base_line={bottom},.dsc=&{name}_dsc}};']
(p.parents[2]/'font_null_jersey.c').write_text('\n'.join(out)+'\n')
