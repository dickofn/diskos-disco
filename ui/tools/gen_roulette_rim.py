#!/usr/bin/env python3
"""Rebuild the exact lossless Roulette wheel resource (requires Pillow)."""
from pathlib import Path
import zlib
from PIL import Image
root=Path(__file__).resolve().parents[1]
im=Image.open(root/'assets/roulette-rim.png').convert('RGBA')
assert im.size==(360,360)
raw=im.tobytes('raw','BGRA');data=zlib.compress(raw,9)
assert zlib.decompress(data)==raw
out='/* SPDX-License-Identifier: GPL-3.0-or-later */\n/* Generated by tools/gen_roulette_rim.py; exact original BGRA pixels. */\n#define ROULETTE_RIM_BYTES (360u*360u*4u)\nstatic const unsigned char rim_deflate[] = {\n'
out+=''.join('    '+','.join('0x%02x'%b for b in data[i:i+16])+',\n' for i in range(0,len(data),16))+'};\n'
(root/'roulette_rim.h').write_text(out)
